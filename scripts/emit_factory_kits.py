#!/usr/bin/env python3
"""Compile the designed kits in kits/*.dfkit into the plugin's factory table.

    python3 scripts/emit_factory_kits.py

Writes Source/Core/FactoryKits.inc, which Parameters.cpp includes inside its kit table.
The .dfkit files stay the editable source of truth; the .inc is generated and should not
be hand-edited.

Ordering matters for session compatibility. The three original kits keep indices 0-2 and
the designed ones are appended, so a session that saved "kit 1" still recalls Warehouse
rather than something else.
"""

import glob
import os
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KIT_DIR = os.path.join(ROOT, "kits")
OUTPUT = os.path.join(ROOT, "Source", "Core", "FactoryKits.inc")

# The KitPresetTrack field order in Parameters.h.
FIELDS = ["level", "pan", "tune", "decay", "tone", "character", "sweep", "drive", "send"]

# Lane prefix -> sort key, so the generated block reads aggressive to calm.
LANE_ORDER = {"IN": 0, "ID": 1, "EL": 2, "AM": 3}


def c_float(text):
    value = float(text)
    # Keep the literal obviously a float, which the table's field types require.
    return f"{value:.1f}f" if value == int(value) else f"{value:.3f}f"


def convert(path):
    root = ET.parse(path).getroot()
    name = root.get("name", "Untitled")
    tracks = {}

    for element in root.findall("TRACK"):
        index = int(element.get("index"))

        if index == 0 and tracks:
            raise SystemExit(f"{path}: tracks are out of order")
        if index in tracks:
            raise SystemExit(f"{path}: duplicate track index {index}")

        depths = {mod.get("target"): float(mod.get("depth")) for mod in element.findall("MOD")}

        # The factory table only carries a level depth. Anything else would be silently
        # dropped on load, so refuse rather than ship a kit that does not sound the same
        # as the one that was designed.
        extra = {k: v for k, v in depths.items() if k != "Level" and abs(v) > 1e-6}

        if extra:
            raise SystemExit(
                f"{path}: track {index} uses modulation the factory table cannot carry: {extra}")

        tracks[index] = (
            int(element.get("model")),
            int(element.get("dist")),
            [float(element.get(field)) for field in FIELDS],
            depths.get("Level", 0.0),
        )

    if len(tracks) != 8:
        raise SystemExit(f"{path}: has {len(tracks)} tracks, expected 8")

    return name, tracks


def main():
    files = sorted(glob.glob(os.path.join(KIT_DIR, "*.dfkit")))

    if not files:
        print(f"no .dfkit files in {KIT_DIR}", file=sys.stderr)
        return 1

    def sort_key(path):
        stem = os.path.splitext(os.path.basename(path))[0]
        lane = stem.split("-")[0].upper()
        return (LANE_ORDER.get(lane, 9), stem)

    lines = [
        "",
        "        // ===================================================================",
        "        // Generated by scripts/emit_factory_kits.py from kits/*.dfkit.",
        "        // Edit the .dfkit files and re-run it; do not hand-edit this block.",
        "        // Field order: model, dist, level, pan, tune, decay, tone,",
        "        //              character, sweep, drive, send, levelDepth",
        "        // ===================================================================",
    ]

    count = 0

    for path in sorted(files, key=sort_key):
        name, tracks = convert(path)
        lines.append(f'        {{ "{name}",')
        lines.append("            {")

        for index in range(8):
            model, dist, values, level_depth = tracks[index]
            # model, dist and the level depth are ints/floats by position: the first two
            # are enum indices, the rest are float parameters.
            fields = [str(model), str(dist)] + [c_float(v) for v in values] + [c_float(level_depth)]
            body = ", ".join(fields)
            comma = "," if index < 7 else ""
            lines.append(f"                {{ {body} }}{comma}")

        lines.append("            }")
        lines.append("        },")
        count += 1

    lines.append("")

    with open(OUTPUT, "w") as handle:
        handle.write("\n".join(lines))

    print(f"wrote {OUTPUT}: {count} kits from {KIT_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
